def _col_to_doc(col: dict) -> str:
    """Render a single column metadata dict as a rich-text document for embedding."""
    parts = [
        f"Column: {col.get('column', '')}",
        f"Type: {col.get('type', '')}",
        f"Description: {col.get('description', '')}",
    ]
    examples = col.get("example_values", [])
    if examples:
        parts.append(f"Example values: {', '.join(str(v) for v in examples)}")
    aliases = col.get("aliases", [])
    if aliases:
        parts.append(f"User may refer to this column as: {', '.join(aliases)}")
    related = col.get("related_columns", [])
    if related:
        parts.append(f"Related columns: {', '.join(related)}")
    return "\n".join(parts)


def _table_to_doc(table: dict) -> str:
    """Render table-level metadata as a rich-text document for embedding."""
    parts = []
    if table.get("description"):
        parts.append(f"Table description: {table['description']}")
    if table.get("grain"):
        parts.append(f"Grain: {table['grain']}")
    if table.get("time_range"):
        parts.append(f"Time range: {table['time_range']}")
    caveats = table.get("caveats", [])
    if caveats:
        parts.append(f"Caveats: {'; '.join(caveats)}")
    return "\n".join(parts)


def store_metadata_in_vectordb(metadata: dict) -> None:
    global _rich_metadata, _metadata_collection
    _rich_metadata = metadata  # keep in-memory for fallback formatting

    # Drop all previously stored metadata documents before re-inserting
    try:
        existing_ids = _metadata_collection.get()["ids"]
        if existing_ids:
            _metadata_collection.delete(ids=existing_ids)
    except Exception as e:
        print(f"[metadata] failed to clear existing documents: {e}")

    documents: list[str] = []
    ids: list[str] = []

    table = metadata.get("table", {})
    if table:
        doc = _table_to_doc(table)
        if doc:
            documents.append(doc)
            ids.append("table_meta")

    for col in metadata.get("columns", []):
        name = col.get("column", "")
        if not name:
            continue
        documents.append(_col_to_doc(col))
        ids.append(f"col_{name}")

    if documents:
        _metadata_collection.add(documents=documents, ids=ids)
        print(f"[metadata] stored {len(documents)} document(s) in vector DB ({len(documents) - 1} columns + 1 table)")


def _retrieve_relevant_metadata(query: str, top_k: int = 6) -> str:
    try:
        count = _metadata_collection.count()
        if count == 0:
            return ""
        results = _metadata_collection.query(
            query_texts=[query],
            n_results=min(top_k, count),
        )
        docs: list[str] = results["documents"][0] if results["documents"] else []
        if not docs:
            return ""
        print(f"[metadata] retrieved {len(docs)} relevant metadata chunk(s)")
        return "\n\n".join(docs)
    except Exception as e:
        print(f"[metadata] retrieval failed, falling back to full metadata dump: {e}")
        # Fallback: format the in-memory copy so the prompt always has some context
        return _format_full_metadata()


def _format_full_metadata() -> str:
    if not _rich_metadata:
        return ""
    parts: list[str] = []
    table = _rich_metadata.get("table", {})
    if table:
        parts.append(_table_to_doc(table))
    for col in _rich_metadata.get("columns", []):
        parts.append(_col_to_doc(col))
    return "\n\n".join(parts)


